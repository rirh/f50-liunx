//! The vendor daemons' device node ownership: Android's `ueventd.rc` and vendor init `chown`/`chmod`, translated.
//!
//! DECLARATIVE DATA, longer than the 500-line guardrail on purpose: one entry per rule, nothing else.
//!
//! How it was derived (keep it generated in spirit): `android/vendor/gen-ueventd-perms.py` reads the device's rules
//! (`android/vendor/ueventd/ueventd.rc` and `init-perms.rc`) and writes `ueventd-perms.sh`; this table is that script,
//! line for line and in its order (a later rule wins over an earlier one for the same node), with its owners kept
//! symbolic: `$V` -> [`V`], `$VG` -> [`VG`], `$GPU` -> [`GPU`], `0` -> [`R`]/[`RG`]. A script line naming two paths is
//! two entries. To regenerate after the generator or its inputs change:
//!
//! ```text
//! python3 android/vendor/gen-ueventd-perms.py android/vendor/ueventd/ueventd.rc android/vendor/ueventd/init-perms.rc \
//!   | grep '^for n in' | awk '<the conversion in this file's history: chown U:G && chmod M -> own(), chown -> chown(),
//!     chmod -> chmod()>'
//! ```
//!
//! What the generator decided, and the reasons (docs/research/FINDINGS.md 41, 41a): Android's `system` and `radio`
//! become the vendor account (uid 1000 where the daemons switch themselves); `graphics` on a node Android gives
//! everyone becomes the `video` group; every other Android id is root; no node keeps bits for others; a node that is
//! root's alone is 0600; input events, `ttyGS*` and the firmware path are root's alone; the RTC stays root's in the
//! vendor group (refnotify opens it). Block devices by number are left out except the RPMB (FINDINGS 31l).

