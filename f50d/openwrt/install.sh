#!/bin/sh
# Installs f50d into an OpenWrt root and takes out the shell programs of the image's overlay that it replaces.
#   install.sh ROOT BINARY [SRC [WEB]]   SRC: this directory (default: where the script is)
#                                        WEB: the web console's build (f50-web/dist), installed as /www/f50
# The image build runs it after everything else is installed.
#
# What stays of /opt/f50: the programs that are not shell (busybox, adbd, logdw, the keys and Bluetooth helpers, the
# carry helper), the vendor chroot (android/: the installer puts it there), the release key and the two helpers
# preinit's early USB DHCP and the first-boot defaults use (f50-lan-ip, f50-device, with /lib/f50/usb-host.sh). The shell programs the installer also takes from systems/base/overlay/opt/f50 (f50-update,
# f50-next-boot, storage.sh, ...) are not part of the running system.
set -eu
R=$1
BIN=$2
SRC=${3:-$(cd "$(dirname "$0")" && pwd)}
WEB=${4:-}
[ -d "$R/etc" ] && [ -x "$BIN" ] || { echo "usage: install.sh ROOT BINARY [SRC [WEB]]" >&2; exit 2; }
[ -z "$WEB" ] || [ -f "$WEB/index.html" ] || { echo "install.sh: $WEB is not a web console build" >&2; exit 2; }

# ------------------------------------------------------------------ f50d
install -D -m 0755 "$BIN" "$R/usr/sbin/f50d"
mkdir -p "$R/usr/libexec/f50d"
ln -sf ../../sbin/f50d "$R/usr/libexec/f50d/modprobe-guard"
for f in "$SRC"/init.d/*; do install -D -m 0755 "$f" "$R/etc/init.d/${f##*/}"; done
for d in iface net misc ntp; do
    for f in "$SRC"/hotplug.d/$d/*; do install -D -m 0755 "$f" "$R/etc/hotplug.d/$d/${f##*/}"; done
done
install -D -m 0755 "$SRC/netifd/f50cell.sh" "$R/lib/netifd/proto/f50cell.sh"
for f in "$SRC"/preinit/*; do install -D -m 0644 "$f" "$R/lib/preinit/${f##*/}"; done
[ -e "$R/etc/config/f50d" ] || install -D -m 0644 "$SRC/config/f50d" "$R/etc/config/f50d"
# the rpcd ACL is generated by the daemon from its method table at its first start (/usr/share/rpcd/acl.d/f50.json)

# the web console (f50-web): static files under /www/f50, the device's front page sends a browser there; LuCI stays
# where it is (/cgi-bin/luci) for OpenWrt's own settings
if [ -n "$WEB" ]; then
    rm -rf "$R/www/f50"
    mkdir -p "$R/www/f50"
    cp -R "$WEB"/. "$R/www/f50/"
    find "$R/www/f50" -type d -exec chmod 0755 {} + && find "$R/www/f50" -type f -exec chmod 0644 {} +
    cat > "$R/www/index.html" <<'HTML'
<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=/f50/"><title>ZTE F50</title></head>
<body><a href="/f50/">ZTE F50</a></body></html>
HTML
fi

# enabled at boot: the S (and K) links rc.common would make
mkdir -p "$R/etc/rc.d"
for f in "$SRC"/init.d/*; do
    name=${f##*/}
    n=$(sed -n 's/^START=//p' "$f"); [ -n "$n" ] && ln -sf "../init.d/$name" "$R/etc/rc.d/S$n$name"
    n=$(sed -n 's/^STOP=//p' "$f"); [ -n "$n" ] && ln -sf "../init.d/$name" "$R/etc/rc.d/K$n$name"
done

# ------------------------------------------------------------------ the shell programs it replaces
# Old init scripts and hooks are named f50-* (f50d's own are f50d*: no pattern here matches them).
for s in "$R"/etc/init.d/f50-*; do
    [ -e "$s" ] || continue
    rm -f "$s" "$R"/etc/rc.d/[SK][0-9][0-9]"${s##*/}"
done
rm -f "$R"/etc/hotplug.d/*/[0-9][0-9]-f50-* "$R"/etc/profile.d/f50.sh "$R"/etc/profile.d/f50-update.sh
# /opt/f50: the shell programs go; programs that are not shell, the chroot and the key stay
for f in "$R"/opt/f50/bin/* "$R"/opt/f50/busybox-bin/*; do
    [ -f "$f" ] && [ ! -L "$f" ] || continue
    case ${f##*/} in f50-lan-ip|f50-device) continue ;; esac
    [ "$(head -c 2 "$f")" = "#!" ] && rm -f "$f"
done
for f in "$R"/opt/f50/lib/*; do
    [ -e "$f" ] || continue
    [ "${f##*/}" = release.pub ] || rm -rf "$f"
done
# the links in /usr/bin to programs that are gone
for l in "$R"/usr/bin/*; do
    [ -L "$l" ] || continue
    case $(readlink "$l") in /opt/f50/bin/*) [ -e "$R$(readlink "$l")" ] || rm -f "$l" ;; esac
done

# ------------------------------------------------------------------ checks
[ -x "$R/usr/sbin/f50d" ] || { echo "f50d is not installed" >&2; exit 1; }
[ -z "$WEB" ] || [ -f "$R/www/f50/index.html" ] || { echo "the web console is not installed" >&2; exit 1; }
for n in S13f50d-at S19f50d S09f50d-vendor S12f50d-hw S99f50d-post; do
    [ -e "$R/etc/rc.d/$n" ] || { echo "f50d: $n is not enabled" >&2; exit 1; }
done
for l in "$R"/etc/rc.d/*f50-*; do
    [ -e "$l" ] || [ -L "$l" ] || continue
    echo "f50d: a service of the shell layer is still enabled: ${l##*/}" >&2
    exit 1
done
echo "f50d installed: $(wc -c < "$R/usr/sbin/f50d") bytes"
